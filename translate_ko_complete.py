def set_nested(d, path, value):
    keys = path.split('.')
    for key in keys[:-1]:
        if key.isdigit():
            d = d[int(key)]
        else:
            d = d[key]
    last = keys[-1]
    if last.isdigit():
        d[int(last)] = value
    else:
        d[last] = value

