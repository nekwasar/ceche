# Count Korean strings
def count_korean(obj):
    count = 0
    if isinstance(obj, dict):
        for v in obj.values():
            count += count_korean(v)
    elif isinstance(obj, list):
        for v in obj:
            count += count_korean(v)
    elif isinstance(obj, str) and obj and len(obj) > 3:
        has_korean = any('\uac00' <= c <= '\ud7af' for c in obj)
        if has_korean:
            count += 1
    return count

korean_count = count_korean(ko)
